/* Generates database/seeds/courses.generated.sql from course-registry.json so
   the SQL catalogue stays byte-consistent with the shipped app. No network. */
'use strict';
const fs = require('fs');
const path = require('path');
const reg = require(path.join(__dirname, '..', 'courses', 'course-registry.json'));
function q(v) { return v == null ? 'null' : "'" + String(v).replace(/'/g, "''") + "'"; }
function slug(cat) { return cat.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+$/,''); }
let out = '-- GENERATED by scripts/build-sql-seed.js. Do not edit by hand.\n';
out += '-- NOT APPLIED to any database in this build environment.\n\n';
reg.courses.forEach(function (c) {
  out += 'insert into courses (id,title,category_id,level,level_label,description,prerequisites,accreditation,certificate_label,unit_count,total_hours,publication_status,version) values (\n  ' +
    [q(c.courseId), q(c.title), q(slug(c.category)), c.level == null ? 'null' : c.level,
     q(c.levelLabel), q(c.description), q(c.prerequisites), q(c.accreditationStatus),
     q(c.certificateLabel), c.unitCount, c.totalHours, q(c.publicationStatus), 1].join(', ') +
    ')\non conflict (id) do update set title=excluded.title, description=excluded.description,\n  unit_count=excluded.unit_count, total_hours=excluded.total_hours, updated_at=now();\n\n';
});
const dst = path.join(__dirname, '..', 'database', 'seeds', 'courses.generated.sql');
fs.writeFileSync(dst, out);
console.log('Wrote ' + reg.courses.length + ' course upserts to ' + dst);
